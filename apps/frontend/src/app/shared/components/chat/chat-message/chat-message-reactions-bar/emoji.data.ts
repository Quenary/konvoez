export interface IEmojiCategory {
  id: string;
  nameKey: string;
  icon: string;
  emojis: string[];
}

export const DEFAULT_QUICK_EMOJIS: string[] = [
  '👍',
  '👎',
  '❤️',
  '🔥',
  '🎉',
  '👏',
  '😂',
  '🤔',
  '😢',
  '💩',
];

const RECENT_EMOJIS_STORAGE_KEY = 'konvoez_recent_emojis';
const MAX_RECENT_EMOJIS = 10;

function getStorage(): Storage | null {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      return window.localStorage;
    }
  } catch {
    // Access denied / restricted
  }
  return null;
}

export function getRecentEmojis(): string[] {
  try {
    const storage = getStorage();
    if (!storage) {
      return [...DEFAULT_QUICK_EMOJIS];
    }
    const raw = storage.getItem(RECENT_EMOJIS_STORAGE_KEY);
    if (!raw) {
      return [...DEFAULT_QUICK_EMOJIS];
    }
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      // Ensure at least 10 items by padding from defaults
      const combined = [...parsed];
      for (const def of DEFAULT_QUICK_EMOJIS) {
        if (!combined.includes(def) && combined.length < MAX_RECENT_EMOJIS) {
          combined.push(def);
        }
      }
      return combined.slice(0, MAX_RECENT_EMOJIS);
    }
  } catch {
    // Ignore storage parse errors
  }
  return [...DEFAULT_QUICK_EMOJIS];
}

export function saveRecentEmoji(emoji: string): void {
  try {
    const storage = getStorage();
    if (!storage) {
      return;
    }
    const current = getRecentEmojis().filter((e) => e !== emoji);
    const updated = [emoji, ...current].slice(0, MAX_RECENT_EMOJIS);
    storage.setItem(RECENT_EMOJIS_STORAGE_KEY, JSON.stringify(updated));
  } catch {
    // Ignore storage quota / access errors
  }
}

